const FORM_ALIASES = {
  ei: 'EI',
  micro: 'MICRO',
  'micro-entreprise': 'MICRO',
  microentreprise: 'MICRO',
  sasu: 'SASU',
  sas: 'SAS',
  eurl: 'EURL',
  sarl: 'SARL',
  sci: 'SCI',
};

export const detectLegalFormKey = (text = '', explicitForm = '') => {
  const explicit = String(explicitForm || '').toUpperCase().replace(/[^A-Z]/g, '');
  if (legalFormDocumentRules[explicit]) return explicit;

  const normalized = String(text).toLowerCase();
  for (const [alias, key] of Object.entries(FORM_ALIASES)) {
    if (normalized.includes(alias)) return key;
  }
  return null;
};

export const formatLegalFormChecklist = (formKey) => {
  const rules = legalFormDocumentRules[formKey];
  if (!rules) return null;

  const lines = [
    `Checklist indicative – ${rules.label} :`,
    '',
    'Pièces fréquentes :',
    ...rules.requiredCommon.map((item) => `• ${item}`),
  ];

  if (rules.conditional?.length) {
    lines.push('', 'Selon votre situation :', ...rules.conditional.map((item) => `• ${item}`));
  }

  if (rules.notes?.length) {
    lines.push('', ...rules.notes.map((note) => `– ${note}`));
  }

  lines.push('', legalFormDocumentRules.meta.warning);
  return lines.join('\n');
};
